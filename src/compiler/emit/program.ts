import type { Analysis } from "../analyze.js";
import { type FieldType, type StructDef } from "../model.js";
import { MAX_ACCOUNTS, cBytes, scalarStorageC, optC, storageDecl, helperSignature, type EmitOptions } from "./shared.js";
import { FunctionEmitter } from "./function.js";

/**
 * The whole C translation unit: type declarations (structs, options, enums, events), every helper and instruction
 * (lowered by FunctionEmitter), and the entry point that dispatches on the instruction discriminator.
 */
export function emitProgram(analysis: Analysis, opts: EmitOptions = {}): string {
  const { model, reporter } = analysis;

  // Bodies first: they register events, string-literal errors and PDA descriptions.
  const helperBodies: string[] = [];
  for (const h of model.helpers.values()) {
    const body = reporter.guard(() => new FunctionEmitter(analysis, h, opts).emitHelper());
    if (body) helperBodies.push(body, "");
  }
  const ixBodies: string[] = [];
  for (const ix of model.instructions) {
    const body = reporter.guard(() => new FunctionEmitter(analysis, ix, opts).emitInstruction());
    if (body) ixBodies.push(body, "");
  }

  const out: string[] = [];
  out.push(`/* Generated by TypeSol from ${analysis.sourceFile.fileName.split("/").pop()}. Do not edit. */`);
  // `const HEAP_SIZE_KIB = 64n`: a larger heap, which clients request with ComputeBudget requestHeapFrame.
  const heap = model.constants.get("HEAP_SIZE_KIB");
  if (heap) {
    if (typeof heap.value !== "bigint" || heap.value < 32n || heap.value > 256n)
      reporter.error(analysis.sourceFile, "HEAP_SIZE_KIB must be an integer from 32 to 256 (the requestHeapFrame limits)");
    else out.push(`#define TS_HEAP_LENGTH (${heap.value}ULL * 1024)`);
  }
  out.push(`#include "typesol_rt.h"`, "");

  for (const inner of model.options.values())
    if (inner.kind !== "struct")
      out.push(`typedef struct __attribute__((packed)) {`, `  uint8_t some;`, `  ${scalarStorageC(inner)} v;`, `} ${optC(inner)};`, "");
  for (const cap of [...model.fstrings].sort((a, b) => a - b))
    out.push(`typedef struct __attribute__((packed)) {`, `  uint32_t len;`, `  uint8_t bytes[${cap}];`, `} TS_FStr${cap};`, "");

  // Structs in dependency order (nested before containing); event-only structs have no C layout.
  const emitted = new Set<string>();
  /** Emit the C typedefs a field type needs (nested structs, Option<struct>, data enums) before its user. */
  const deps = (t: FieldType): void => {
    if (t.kind === "struct") emitStruct(model.structs.get(t.name)!);
    if (t.kind === "array" || t.kind === "vec") deps(t.elem);
    if (t.kind === "option" && t.inner.kind === "struct") {
      const key = `opt:${t.inner.name}`;
      if (emitted.has(key)) return;
      emitStruct(model.structs.get(t.inner.name)!);
      emitted.add(key);
      out.push(`typedef struct __attribute__((packed)) {`, `  uint8_t some;`, `  TSS_${t.inner.name} v;`, `} ${optC(t.inner)};`, "");
    }
    if (t.kind === "dataEnum") {
      const key = `enum:${t.name}`;
      if (emitted.has(key)) return;
      emitted.add(key);
      const e = model.dataEnums.get(t.name)!;
      for (const v of e.variants) v.fields.forEach((f) => deps(f.type));
      for (const v of e.variants) {
        out.push(`typedef struct __attribute__((packed)) {`);
        for (const f of v.fields) out.push(`  ${storageDecl(f.type, f.name)};`);
        if (!v.fields.length) out.push(`  uint8_t __unit[0];`);
        out.push(`} TSV_${e.name}__${v.name};`);
      }
      out.push(`typedef struct __attribute__((packed)) {`, `  uint8_t tag;`, `  union __attribute__((packed)) {`);
      for (const v of e.variants) out.push(`    TSV_${e.name}__${v.name} ${v.name};`);
      out.push(`    uint8_t __bytes[${e.payload}];`, `  } v;`, `} TSE_${e.name};`);
      out.push(`_Static_assert(sizeof(TSE_${e.name}) == ${1 + e.payload}, "TSE_${e.name} layout");`, "");
    }
  };
  const emitStruct = (s: StructDef) => {
    if (emitted.has(s.name) || s.size === undefined) return;
    emitted.add(s.name);
    s.fields.forEach((f) => deps(f.type));
    out.push(`typedef struct __attribute__((packed)) {`);
    for (const f of s.fields) out.push(`  ${storageDecl(f.type, f.name)};`);
    out.push(`} TSS_${s.name};`);
    out.push(`_Static_assert(sizeof(TSS_${s.name}) == ${s.size}, "TSS_${s.name} layout");`);
    if (s.vec) out.push(`#define TS_ELEM_${s.name} ${s.vec.elemSize}`);
    if (model.accountStructs.has(s.name)) out.push(`static const uint8_t TS_DISC_${s.name}[8] = ${cBytes(s.accountDiscriminator)};`);
    out.push("");
  };
  for (const s of model.structs.values()) emitStruct(s);
  for (const e of model.dataEnums.values()) deps({ kind: "dataEnum", name: e.name });

  for (const k of model.constants.values()) if (typeof k.value === "object") out.push(`static const SolPubkey TSK_${k.name} = {${cBytes(k.value.pubkey)}};`);
  const helpers = [...model.helpers.values()];
  for (const h of helpers) out.push(helperSignature(h) + ";");
  if (helpers.length) out.push("");
  out.push(...helperBodies, ...ixBodies);

  out.push(`#define TS_MAX_ACCOUNTS ${MAX_ACCOUNTS}`);
  out.push(`extern uint64_t entrypoint(const uint8_t *input) {`);
  out.push(`  SolAccountInfo ka[TS_MAX_ACCOUNTS];`);
  out.push(`  SolParameters params;`, `  params.ka = ka; /* ts_deserialize fills in the rest */`);
  // Clamping the count to what fits would make extra accounts silently vanish from remainingAccounts():
  // refuse more than the array holds instead (ts_deserialize relies on this bound).
  out.push(`  if (*(const uint64_t *)input > TS_MAX_ACCOUNTS) TS_FAIL(TS_ERR_TOO_MANY_ACCOUNTS, "TypeSol: at most ${MAX_ACCOUNTS} accounts per instruction");`);
  out.push(`  ts_deserialize(input, &params);`);
  const minDisc = Math.min(8, ...model.instructions.map((ix) => ix.discriminator.length));
  out.push(`  if (params.data_len < ${minDisc}) TS_FAIL(TS_ERR_INSTRUCTION_MISSING, "TypeSol: instruction data too short");`);
  // Self-CPI events (emitCpi): accept the event instruction when its authority PDA signed it, like Anchor.
  if (model.instructions.some((ix) => ix.accounts.some((a) => a.kind.kind === "eventAuthority")))
    out.push(`  if (params.data_len >= 8 && ts_mem_eq(params.data, TS_EVENT_IX_TAG, 8)) return ts_event_dispatch(&params);`);
  for (const ix of model.instructions) {
    const n = ix.discriminator.length;
    // An 8-byte discriminator is one u64 compare (the data is little-endian bytes, the literal their u64 value).
    if (n === 8) {
      const word = [...ix.discriminator].reverse().reduce((v, b) => (v << 8n) | BigInt(b), 0n);
      out.push(`  if (params.data_len >= 8 && ts_ld64(params.data) == 0x${word.toString(16).padStart(16, "0")}ULL) return ix_${ix.name}(&params);`);
      continue;
    }
    out.push(`  {`);
    out.push(`    static const uint8_t disc[${n}] = ${cBytes(ix.discriminator)};`);
    out.push(`    if (params.data_len >= ${n} && ts_mem_eq(params.data, disc, ${n})) return ix_${ix.name}(&params);`);
    out.push(`  }`);
  }
  out.push(`  TS_FAIL(TS_ERR_INSTRUCTION_NOT_FOUND, "TypeSol: unknown instruction");`);
  out.push(`}`);
  return out.join("\n") + "\n";
}
